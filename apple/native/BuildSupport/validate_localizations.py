#!/usr/bin/env python3
"""Build/validate eight explicit catalogs. Never silently fill untranslated UI keys."""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
LANGUAGES = ('es', 'en', 'zh-Hans', 'hi', 'ar', 'fr', 'de', 'it')
# Proper names, product labels and license identifiers deliberately remain literal.
INVARIANT = {
    'VETA', 'VETA Retro', 'RETRO', 'Saturn', 'Metal', 'FCEUmm', 'Libretro Thumbnails',
    'FCEUmm · ac0d00a · GNU GPL v2', 'mGBA · 0.10.5 · MPL 2.0',
    'Genesis Plus GX · Stella 2014 · Beetle PCE Fast · PCSX ReARMed · DeSmuME · Beetle Saturn',
}
CALL = re.compile(r'(?:Text|Label|Button|Section|Toggle|Picker|Menu|TextField|ProgressView|NavigationLink|Link|navigationTitle|accessibilityLabel|accessibilityHint|alert|confirmationDialog|LabeledContent|L10n\.(?:text|format))\(\s*"((?:\\.|[^"\\])*)"')

def rows():
    result = {}
    for number, line in enumerate((ROOT/'BuildSupport/localization-translations.tsv').read_text().splitlines(), 1):
        values = line.split('\t')
        if len(values) != len(LANGUAGES) or any(not value.strip() for value in values):
            raise ValueError(f'Invalid translation row {number}: expected eight nonempty values')
        if values[0] in result:
            raise ValueError(f'Duplicate translation: {values[0]}')
        result[values[0]] = values
    for key in INVARIANT:
        result[key] = [key] * len(LANGUAGES)
    return result

ERROR = re.compile(r'VetaError\.message\(\s*"((?:\\.|[^"\\])*)"')
# Dreamcast error factories are not SwiftUI calls. Scope the unqualified
# factory and enum-return patterns to these files to avoid unrelated literals.
DREAMCAST_FAILURE = re.compile(r'(?:DreamcastWebAssets\.)?failure\(\s*"((?:\\.|[^"\\])*)"')
DREAMCAST_RETURN = re.compile(r'case\s+\.\w+\s*:\s*return\s+"((?:\\.|[^"\\])*)"')
# Legacy completed messages are localized through L10n's bounded templates.
INTERPOLATION = re.compile(r'\\\([^)]*\)')

MESSAGE = re.compile(r'(?:\b(?:error|failure|message|status)|messages\[[^\]]+\])\s*=\s*"((?:\\.|[^"\\])*)"')

def required_keys():
    keys = set()
    for source in (ROOT/'Sources').glob('*.swift'):
        content = source.read_text()
        for match in list(ERROR.finditer(content)) + list(MESSAGE.finditer(content)):
            if match[1]:
                keys.add(INTERPOLATION.sub('%@', match[1]))
        if source.name in ('DreamcastWebServer.swift', 'DreamcastWebLaunchPolicy.swift'):
            keys.update(INTERPOLATION.sub('%@', match[1]) for match in DREAMCAST_FAILURE.finditer(content) if match[1])
        if source.name == 'DreamcastWebVMUStore.swift':
            keys.update(INTERPOLATION.sub('%@', match[1]) for match in DREAMCAST_RETURN.finditer(content) if match[1])
        if source.name == 'Localization.swift':
            keys.update(re.findall(r'\.init\(key: "([^"\n]+)"', content))
        for match in CALL.finditer(content):
            key = match[1]
            if key and '\\(' not in key:
                keys.add(key)
    for game in json.loads((ROOT/'Sources/DiscoveryCatalog.json').read_text()):
        keys.update(game[field] for field in ('summary', 'note') if game.get(field))
    return keys

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    translations = rows()
    missing = sorted(required_keys() - translations.keys())
    if missing:
        print(json.dumps({'missing_static_UI_keys': missing}, ensure_ascii=False, indent=2))
        return 1
    placeholders = re.compile(r'%(?:\d+\$)?(?:lld|ld|d|u|f|@|%)')
    for key, values in translations.items():
        expected = sorted(placeholders.findall(key))
        for code, value in zip(LANGUAGES, values):
            if sorted(placeholders.findall(value)) != expected:
                raise ValueError(f'Placeholder mismatch: {code}: {key}')
    for index, code in enumerate(LANGUAGES):
        content = '// Generated by BuildSupport/validate_localizations.py --write; edit the TSV source.\n'
        content += ''.join(f'{json.dumps(key, ensure_ascii=False)} = {json.dumps(values[index], ensure_ascii=False)};\n' for key, values in sorted(translations.items()))
        path = ROOT/'Sources/Resources'/f'{code}.lproj'/'Localizable.strings'
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        elif not path.exists() or path.read_text() != content:
            raise ValueError(f'Catalog stale or absent: {path}')
    print(f'Validated {len(translations)} keys across {len(LANGUAGES)} languages; static UI, discovery content, app error templates and placeholders match.')
    return 0

if __name__ == '__main__':
    sys.exit(main())
